// Chaque élément porteur de data-st ne paraît que dans les états qu'il nomme.
;(function () {
  const switcher = document.querySelector('.state-switch')
  if (!switcher) return
  const params = new URLSearchParams(location.search)
  const fallback = switcher.dataset.default
  const state = params.get('etat') || fallback
  const dark = params.get('theme') === 'dark'
  document.body.dataset.state = state
  document.querySelectorAll('[data-st]').forEach((el) => { el.hidden = !el.dataset.st.split(' ').includes(state) })
  document.querySelectorAll('[data-st-not]').forEach((el) => { el.hidden = el.dataset.stNot.split(' ').includes(state) })
  // Les liens d'état gardent le thème choisi.
  document.querySelectorAll('a[data-etat]').forEach((a) => {
    a.href = '?etat=' + a.dataset.etat + (dark ? '&theme=dark' : '')
    if (a.dataset.etat === state && a.closest('.state-switch')) a.setAttribute('aria-current', 'page')
  })
  document.querySelectorAll('a[data-page]').forEach((a) => {
    a.href = a.dataset.page + (dark ? (a.dataset.page.includes('?') ? '&' : '?') + 'theme=dark' : '')
  })
})()
