// ---------------------------------------------------------------------------
// Rattachement des entités aux thématiques
//
// `reference.entity_terms` est polymorphe : le triplet (schéma, table, id) est
// posé par le service, jamais par le formulaire — c'est l'exigence inscrite au
// prompt B4. Les thématiques d'une proposition ne vivent donc PAS sur la
// proposition ; l'écran les lit ici.
// ---------------------------------------------------------------------------

/** Rattache une entité de `programme` à ses thématiques, dans l'ordre affiché. */
function themesOf(table: 'proposals' | 'sessions', entityId: string, termIds: string[]): EntityTerm[] {
  return termIds.map((term_id, index) => ({
    entity_schema: 'programme',
    entity_table: table,
    entity_id: entityId,
    term_id,
    role: index === 0 ? 'primary' : 'secondary',
    sort_order: (index + 1) * 10,
    created_at: '2026-06-18T10:00:00Z',
  }))
}

